const CODE_SET = new Set(COUNTRY_CODES);

/** True for a code the backend accepts. */
export function isCountryCode(code: string): boolean {
  return CODE_SET.has(code);
}

/** The English name of a country ("Kenya"), or its code when the browser has no name for it. */
export function countryName(code: string): string {
  try {
    const name = new Intl.DisplayNames(["en"], { type: "region" }).of(code);
    return name && name !== code ? name : code;
  } catch {
    return code;
  }
}

/** Dropdown options: Rwanda first, then every other country by name. */
export function countryOptions(): { value: string; label: string }[] {
  const others = COUNTRY_CODES.filter((c) => c !== RWANDA)
    .map((c) => ({ value: c, label: countryName(c) }))
    .sort((a, b) => a.label.localeCompare(b.label, "en"));
  return [{ value: RWANDA, label: countryName(RWANDA) }, ...others];
}
